CREATE TABLE IF NOT EXISTS users (
  id UUID NOT NULL PRIMARY KEY DEFAULT UUID_V7(),
  disabled BOOLEAN NOT NULL DEFAULT TRUE,
  username VARCHAR(255) NOT NULL,
  email_address VARCHAR(255) NOT NULL,
  first_name VARCHAR(255) NOT NULL,
  last_name VARCHAR(255) NOT NULL,
  pass BINARY(64) NOT NULL,
  totp_secret BLOB NOT NULL
);

CREATE TABLE IF NOT EXISTS email_verification (
  token BINARY(8) NOT NULL PRIMARY KEY,
  user_id UUID NOT NULL,
  expires_at TIMESTAMP NOT NULL DEFAULT TIMESTAMPADD(DAY, 1, NOW()),
  FOREIGN KEY (user_id) REFERENCES users(id)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS sessions (
  id BINARY(8) NOT NULL PRIMARY KEY,
  user_id UUID NOT NULL,
  expires_at TIMESTAMP NOT NULL DEFAULT TIMESTAMPADD(SECOND, 90, NOW()),
  FOREIGN KEY (user_id) REFERENCES users(id)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS categories (
  id UUID NOT NULL PRIMARY KEY DEFAULT UUID_V7(),
  user_id UUID,
  name VARCHAR(255) NOT NULL UNIQUE,
  FOREIGN KEY (user_id) REFERENCES users(id)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS transaction_records (
  id UUID NOT NULL PRIMARY KEY DEFAULT UUID_V7(),
  user_id UUID NOT NULL,
  title VARCHAR(255) NOT NULL,
  category_id UUID NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW() ON UPDATE CURRENT_TIMESTAMP,
  value INT NOT NULL,
  description TEXT,
  FOREIGN KEY (category_id) REFERENCES categories(id)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS repeating_transactions (
  id UUID NOT NULL PRIMARY KEY DEFAULT UUID_V7(),
  user_id UUID NOT NULL,
  title VARCHAR(255) NOT NULL,
  category_id UUID NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW() ON UPDATE CURRENT_TIMESTAMP,
  repeats_at TIMESTAMP NOT NULL,
  value INT NOT NULL,
  description TEXT,
  FOREIGN KEY (category_id) REFERENCES categories(id)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);
